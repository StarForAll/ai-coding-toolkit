def normative(name):
    section = ''
    enabled = False
    for n, line in enumerate(TEXTS[name].splitlines(), 1):
        if line.startswith('## 附录') or (name == FILES[1] and line.startswith('## 14.')):
            break
        if line.startswith('## 0.') or (name == FILES[1] and line.startswith('## 1.')):
            enabled = True
        if line.startswith('#'):
            section = line
        if enabled:
            yield {'line': n, 'section': section, 'text': line}


def safe(text):
    return text.replace('|', '∣').replace('\n', ' ')


